FREQTRADE_STRATEGY = '''\
"""NEUTRAL_MA_CROSS_1H — the parity rule, transcribed without tuning.

Long while talib.EMA(12) > talib.EMA(26) on the previous closed candle, flat
otherwise. Freqtrade acts on a signal at the close of candle i by filling at the
open of candle i+1, which is the same fill timing this project's backtester uses,
so the two engines are compared on one convention rather than two.

This file is generated by scripts/edge14r_engine_parity.py. It is a transcription
of a rule, not a strategy: it holds no fitted parameter and claims no edge.
"""

import talib.abstract as ta
from freqtrade.strategy import IStrategy


class NeutralMaCross(IStrategy):
    INTERFACE_VERSION = 3

    timeframe = "1h"
    can_short = False

    # Nothing but the rule itself may close a trade: a stop or a ROI target would
    # be a second exit path this project's side does not have, and it would show
    # up as an engine difference when it is really a model difference.
    minimal_roi = {"0": 1000}
    stoploss = -0.99
    trailing_stop = False
    use_exit_signal = True
    exit_profit_only = False
    ignore_roi_if_entry_signal = False

    # talib.EMA(26) is defined from the 26th candle, i.e. index 25, so the engine
    # must be told it needs 25 startup candles. Declaring 26 would silently drop
    # one evaluable candle and shift the whole trade list by one bar, which shows
    # up as a first-trade timestamp mismatch rather than as the warm-up bug it is.
    startup_candle_count = 25
    process_only_new_candles = True

    def populate_indicators(self, dataframe, metadata):
        dataframe["ema_fast"] = ta.EMA(dataframe, timeperiod=12)
        dataframe["ema_slow"] = ta.EMA(dataframe, timeperiod=26)
        return dataframe

    def populate_entry_trend(self, dataframe, metadata):
        dataframe.loc[
            (dataframe["ema_fast"] > dataframe["ema_slow"]),
            "enter_long",
        ] = 1
        return dataframe

    def populate_exit_trend(self, dataframe, metadata):
        dataframe.loc[
            (dataframe["ema_fast"] < dataframe["ema_slow"]),
            "exit_long",
        ] = 1
        return dataframe
'''


