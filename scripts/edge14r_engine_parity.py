"""edge14r_engine_parity — run the external engine for real and diff the engines.

The external engine is installed in its own virtual environment outside this
checkout, and is invoked as a subprocess.  Nothing external is imported into the
runtime, no external code is copied into the tree, and the engine's own licence
(and any copyleft in it) stays on its side of the boundary.

Usage:
    python scripts/edge14r_engine_parity.py --engine freqtrade --manifest <path>

The engine's workspace is created under ``%TEMP%/edge14r/parity/<engine>`` and is
reproducible from the dataset snapshot the run names; it is not committed.
"""

