"""Combine PAPER + FORWARD DATA + STRATEGY LAB into one SYSTEM_DAILY_REPORT (§15, §47).

The three planes already publish their own reports, and deliberately so: each one
is generated by a process that knows its own numbers. This script does not
recompute any of them. It reads what each plane wrote, folds the answers into one
document an operator can read in the morning, and — where a plane produced
nothing — says so instead of printing a zero that could be mistaken for success.

    uv run python scripts/system_daily_report.py --lab-run-dir reports/paper-lab/<run-id>

Nothing here is a control path: it opens files for reading and writes two report
files. Running it (or not running it) cannot change a decision, a strategy or a
capture.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from trading_bot.autonomous.paper_loop import (  # noqa: E402
    PAPER_DAILY_REPORT_SCHEMA_VERSION,
)

SYSTEM_REPORT_SCHEMA_VERSION = "system-daily-report-v1"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lab-run-dir", required=True, help="the supervisor run directory")
    parser.add_argument("--paper-run-dir", default=None, help="the PAPER run directory")
    parser.add_argument("--forward-root", default="reports/microstructure-forward-lab")
    parser.add_argument("--forward-run-id", default=None)
    parser.add_argument("--lab-report", default=None, help="STRATEGY_LAB_REPORT.json")
    parser.add_argument("--out", default=None, help="default <lab-run-dir>/SYSTEM_DAILY_REPORT")
    return parser.parse_args()


def _read_json(path: Path) -> dict[str, Any] | None:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return payload if isinstance(payload, dict) else None


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    rows: list[dict[str, Any]] = []
    try:
        with path.open("r", encoding="utf-8") as handle:
            for line in handle:
                line = line.strip()
                if line:
                    rows.append(json.loads(line))
    except (OSError, ValueError):
        return rows
    return rows


def _live_state_path(root: Path, manifest_path: Path | None) -> Path:
    """The collector's live state file: what is true while it is still running."""
    run_id = manifest_path.stem if manifest_path else None
    if run_id:
        candidate = root / "state" / f"{run_id}.json"
        if candidate.exists():
            return candidate
    state_dir = root / "state"
    if state_dir.exists():
        candidates = sorted(state_dir.glob("*.json"), key=lambda p: p.stat().st_mtime)
        if candidates:
            return candidates[-1]
    return root / "heartbeat.json"


def newest_child(root: Path) -> Path | None:
    if not root.exists():
        return None
    children = [path for path in root.iterdir() if path.is_dir()]
    if not children:
        return None
    return max(children, key=lambda path: path.stat().st_mtime)


def collect_paper(paper_run_dir: Path | None, root: Path) -> dict[str, Any]:
    """Everything the PAPER plane knows, including "it never started"."""
    run_dir = paper_run_dir or newest_child(root)
    if run_dir is None:
        return {
            "present": False,
            "reason": f"no PAPER run directory under {root}",
            "daily_report": None,
        }
    daily = _read_json(run_dir / "PAPER_DAILY_REPORT.json")
    heartbeat = _read_json(run_dir / "heartbeat.json")
    run_report = _read_json(run_dir / "RUN_REPORT.json")
    beats = _read_jsonl(run_dir / "heartbeat.jsonl")
    outcomes = _read_jsonl(run_dir / "outcomes.jsonl")
    resolved = [o for o in outcomes if o.get("status") == "RESOLVED"]
    return {
        "present": daily is not None or heartbeat is not None or bool(beats),
        "run_dir": str(run_dir),
        "daily_report_path": str(run_dir / "PAPER_DAILY_REPORT.json"),
        "daily_report_schema": (daily or {}).get("schema_version"),
        "expected_schema": PAPER_DAILY_REPORT_SCHEMA_VERSION,
        "heartbeats": len(beats),
        "cycles": int((daily or {}).get("cycles", 0)),
        "decisions": int((daily or {}).get("decisions", 0)),
        "no_trade": int((daily or {}).get("no_trade", 0)),
        "no_trade_kinds": (daily or {}).get("no_trade_kinds", {}),
        "shadow_trades": int((daily or {}).get("shadow_trades", 0)),
        "paper_trades": int((daily or {}).get("paper_trades", 0)),
        "orders_created": int((daily or {}).get("orders_created", 0)),
        "risk_events": (daily or {}).get("risk_events", {}),
        "runtime_failures": int((daily or {}).get("runtime_failures", 0)),
        "paper_candidates": (daily or {}).get("paper_candidates", []),
        "outcomes_resolved": len(resolved),
        "outcomes_pending": int((daily or {}).get("pnl", {}).get("pending_outcomes", 0)),
        "pnl_gross_bps_total": (daily or {}).get("pnl", {}).get("gross_bps_total"),
        "strategy_attribution": (daily or {}).get("strategy_attribution", {}),
        "last_cycle": heartbeat.get("cycle") if heartbeat else None,
        "state_age_seconds": heartbeat.get("state_age_seconds") if heartbeat else None,
        "mode": (daily or {}).get("mode", (heartbeat or {}).get("mode")),
        "errors": (daily or {}).get("errors", []),
        "run_report_state": (run_report or {}).get("status") or (run_report or {}).get("state"),
    }


def collect_forward(
    root: Path, run_id: str | None, heartbeat_path: Path | None = None
) -> dict[str, Any]:
    """Collector rows, gaps and reconnects, read from its own manifest."""
    manifest_dir = root / "manifest"
    manifest_path: Path | None = None
    if run_id:
        candidate = manifest_dir / f"{run_id}.json"
        manifest_path = candidate if candidate.exists() else None
    else:
        candidates = sorted(manifest_dir.glob("*.json"), key=lambda p: p.stat().st_mtime)
        manifest_path = candidates[-1] if candidates else None
    manifest = _read_json(manifest_path) if manifest_path else None
    if heartbeat_path is None:
        heartbeat_path = _live_state_path(root, manifest_path)
    live = _read_json(heartbeat_path)
    if manifest is None:
        # A capture that is still running has no manifest yet; its heartbeat does.
        return {
            "present": live is not None,
            "manifest_path": None,
            "reason": (
                f"no manifest under {manifest_dir}; the capture may still be running"
                if root.exists()
                else f"{root} does not exist"
            ),
            "heartbeat": live,
        }
    gaps = manifest.get("gaps", []) or []
    integrity = manifest.get("integrity", {}) or {}
    fingerprints = manifest.get("fingerprints", []) or []
    latency = _latency_from_quality_report(root)
    return {
        "present": True,
        "manifest_path": str(manifest_path),
        "run_id": manifest.get("run_id"),
        "commit": manifest.get("commit"),
        "continuity": manifest.get("continuity"),
        "started_at": manifest.get("started_at"),
        "ended_at": manifest.get("ended_at"),
        "duration_seconds": manifest.get("duration_seconds"),
        "rotation_seconds": manifest.get("rotation_seconds"),
        "row_count": sum(int(f.get("row_count", 0)) for f in fingerprints),
        "segment_count": len(fingerprints),
        "partial_tails": sum(1 for f in fingerprints if f.get("partial_tail")),
        "bytes_written": manifest.get("bytes_written"),
        "gaps": len(gaps),
        "unrecoverable_gaps": sum(1 for g in gaps if g.get("status") == "UNRECOVERABLE"),
        "recovered_gaps": sum(1 for g in gaps if str(g.get("status", "")).startswith("RECOVERED")),
        "gaps_data_lost": sum(1 for g in gaps if g.get("data_lost")),
        "backfilled_events": integrity.get("backfilled_events"),
        "backfill_gaps_closed": integrity.get("backfill_gaps_closed"),
        "backfill_failures": integrity.get("backfill_failures"),
        "reconnects": manifest.get("reconnects"),
        "resnapshots": manifest.get("resnapshots"),
        "connect_failures": integrity.get("connect_failures"),
        "degradation_events": len(manifest.get("degradation_events", []) or []),
        "stopped_on_disk_budget": bool(manifest.get("stopped_on_disk_budget")),
        "resources": manifest.get("resources", {}),
        "latency_source": latency.get("source"),
        "latency_p50_ms": latency.get("p50_ms"),
        "latency_p95_ms": latency.get("p95_ms"),
        "latency_p99_ms": latency.get("p99_ms"),
        "heartbeat": live,
    }


def _latency_from_quality_report(root: Path) -> dict[str, Any]:
    """Latency percentiles live in the read-side quality report, not the manifest.

    The manifest is written by the capture process and deliberately holds only
    what the writer observed; the distribution over the persisted rows is a
    read-side product. Reporting ``None`` when the report has not been generated
    is the honest answer, so it is preferred over guessing from the writer.
    """
    for candidate in (root / "reports" / "FORWARD_DATA_QUALITY_REPORT.json",):
        payload = _read_json(candidate)
        if payload is None:
            continue
        latency = payload.get("event_latency_ms")
        if isinstance(latency, dict):
            return {
                "source": str(candidate),
                "p50_ms": latency.get("p50_ms"),
                "p95_ms": latency.get("p95_ms"),
                "p99_ms": latency.get("p99_ms"),
            }
    return {"source": None}


def collect_strategy_lab(path: Path | None, forward_root: Path) -> dict[str, Any]:
    report = _read_json(path) if path else None
    if report is None and forward_root.exists():
        fallback = forward_root / "STRATEGY_LAB_REPORT.json"
        report = _read_json(fallback)
    if report is None:
        return {
            "present": False,
            "reason": (
                "the strategy lab has not published a report; "
                "0 experiments and 0 candidates is a valid result but must not be assumed"
            ),
        }
    return {
        "present": True,
        "path": str(path) if path else None,
        "timestamp_ms": report.get("timestamp_ms"),
        "lifecycle": report.get("lifecycle", {}),
        "paper_executable": report.get("paper_executable", []),
        "all_checks_ok": report.get("all_checks_ok"),
        "checks": {
            key: bool(value.get("ok")) if isinstance(value, dict) else bool(value)
            for key, value in (report.get("checks", {}) or {}).items()
        },
        "pre_registration": (report.get("checks", {}) or {}).get("microstructure_hypotheses"),
        "mode": report.get("mode"),
    }


def build_report(args: argparse.Namespace) -> dict[str, Any]:
    lab_run_dir = (REPO_ROOT / args.lab_run_dir).resolve()
    forward_root = (REPO_ROOT / args.forward_root).resolve()
    paper_root = REPO_ROOT / "reports" / "autonomous-paper"
    paper_run_dir = (
        (REPO_ROOT / args.paper_run_dir).resolve() if args.paper_run_dir else None
    )
    lab_report = (REPO_ROOT / args.lab_report).resolve() if args.lab_report else None

    supervisor = _read_json(lab_run_dir / "SYSTEM_HEARTBEAT.json")
    lab_run = _read_json(lab_run_dir / "LAB_RUN_REPORT.json")
    declared_heartbeat = forward_root / "state" / f"{lab_run_dir.name}.json"
    forward_heartbeat = declared_heartbeat if declared_heartbeat.exists() else None
    payload: dict[str, Any] = {
        "schema_version": SYSTEM_REPORT_SCHEMA_VERSION,
        "generated_at_ms": int(time.time() * 1000),
        "lab_run_dir": str(lab_run_dir),
        "mode": "PAPER ONLY — no live path, no real capital",
        "supervisor": {
            "present": supervisor is not None,
            "state": (supervisor or {}).get("state"),
            "processes": (supervisor or {}).get("processes", {}),
            "disk_free_bytes": (supervisor or {}).get("disk_free_bytes"),
            "memory_mb": (supervisor or {}).get("memory_mb"),
            "children": (supervisor or {}).get("children", {}),
        },
        "lab_run": {
            "present": lab_run is not None,
            "duration_seconds": (lab_run or {}).get("duration_seconds"),
            "stop_reason": (lab_run or {}).get("stop_reason"),
            "final_state": (lab_run or {}).get("final_state"),
            "supervisor_events": (lab_run or {}).get("supervisor_events", []),
        },
        "paper": collect_paper(paper_run_dir, paper_root),
        "forward_data": collect_forward(
            forward_root, args.forward_run_id, heartbeat_path=forward_heartbeat
        ),
        "strategy_lab": collect_strategy_lab(lab_report, forward_root),
    }

    restarts = [
        event
        for event in payload["lab_run"]["supervisor_events"]
        if str(event.get("event", "")).startswith(("RESTART", "CRASH_LOOP"))
    ]
    failures = [
        event
        for event in payload["lab_run"]["supervisor_events"]
        if str(event.get("event")) == "CRASH_LOOP"
    ]
    payload["operations"] = {
        "restarts": len(restarts),
        "crash_loops": len(failures),
        "restart_events": restarts[:50],
        "paper_and_collector_isolated": (
            "PAPER and the collector run as separate processes supervised "
            "independently; neither is in the other's failure domain"
        ),
        "no_live_path": (
            "the launcher starts read-only market data plus the PAPER broker; "
            "no child holds execution credentials and LIVE is not reachable"
        ),
    }
    payload["planes_present"] = {
        "paper": bool(payload["paper"]["present"]),
        "forward_data": bool(payload["forward_data"]["present"]),
        "strategy_lab": bool(payload["strategy_lab"]["present"]),
        "supervisor": bool(payload["supervisor"]["present"]),
    }
    payload["honesty_notes"] = [
        note
        for note in (
            None
            if payload["paper"]["present"]
            else "PAPER produced no report: this is absence of evidence, not a pass.",
            None
            if payload["forward_data"]["present"]
            else "the collector produced no manifest: no rows can be claimed.",
            (
                "the strategy lab reports 0 experiments and 0 candidates: that is the "
                "real result, not a placeholder."
                if payload["strategy_lab"]["present"]
                and not payload["strategy_lab"].get("paper_executable")
                else None
            ),
            (
                "collector latency percentiles come from the read-side quality "
                "report; until it is generated this report prints None rather than "
                "re-deriving them."
                if payload["forward_data"].get("manifest_path")
                and not payload["forward_data"].get("latency_source")
                else None
            ),
        )
        if note
    ]
    return payload


def render_system_markdown(payload: dict[str, Any]) -> str:
    paper = payload["paper"]
    forward = payload["forward_data"]
    lab = payload["strategy_lab"]
    supervisor = payload["supervisor"]
    lines = [
        "# SYSTEM DAILY REPORT",
        "",
        "```text",
        f"generated : {payload['generated_at_ms']}",
        f"lab run   : {payload['lab_run_dir']}",
        f"mode      : {payload['mode']}",
        f"supervisor: {supervisor.get('state')}",
        "planes    : " + " ".join(f"{k}={v}" for k, v in payload["planes_present"].items()),
        "```",
        "",
        "## PAPER",
        "",
    ]
    if paper["present"]:
        lines += [
            "```text",
            f"cycles        : {paper.get('cycles')}",
            f"decisions     : {paper.get('decisions')}",
            f"NO_TRADE      : {paper.get('no_trade')}",
            f"SHADOW        : {paper.get('shadow_trades')}",
            f"PAPER trades  : {paper.get('paper_trades')}",
            f"orders        : {paper.get('orders_created')}",
            f"failures      : {paper.get('runtime_failures')}",
            f"candidates    : {', '.join(paper.get('paper_candidates') or []) or 'NONE'}",
            f"last cycle    : {paper.get('last_cycle')}",
            "```",
            "",
        ]
    else:
        lines += [f"_No PAPER report: {paper.get('reason')}_", ""]

    lines += ["## FORWARD DATA", ""]
    if forward.get("manifest_path"):
        heartbeat = forward.get("heartbeat") or {}
        lines += [
            "```text",
            f"run_id        : {forward.get('run_id')} ({forward.get('continuity')})",
            f"rows          : {forward.get('row_count')}",
            f"segments      : {forward.get('segment_count')} (partial tails {forward.get('partial_tails')})",
            f"duration_s    : {forward.get('duration_seconds')}",
            f"gaps          : {forward.get('gaps')} (unrecoverable {forward.get('unrecoverable_gaps')})",
            f"backfilled    : {forward.get('backfilled_events')} events / "
            f"{forward.get('backfill_gaps_closed')} gaps (failures {forward.get('backfill_failures')})",
            f"reconnects    : {forward.get('reconnects')}  resnapshots: {forward.get('resnapshots')}",
            f"latency p50/95/99 ms: {forward.get('latency_p50_ms')} / "
            f"{forward.get('latency_p95_ms')} / {forward.get('latency_p99_ms')}"
            + ("" if forward.get("latency_source") else "  (no read-side quality report yet)"),
            f"disk-budget stop: {forward.get('stopped_on_disk_budget')}",
            f"live state    : events={heartbeat.get('events')} "
            f"reconnects={heartbeat.get('reconnects')} gaps={heartbeat.get('gaps')}",
            "```",
            "",
        ]
    elif forward["present"]:
        heartbeat = forward.get("heartbeat") or {}
        lines += [
            "_The capture has not finalised yet (no manifest); its live state is:_",
            "",
            "```text",
            f"run_id     : {heartbeat.get('run_id')}",
            f"events     : {heartbeat.get('events')}",
            f"reconnects : {heartbeat.get('reconnects')}",
            f"resnapshots: {heartbeat.get('resnapshots')}",
            f"gaps       : {heartbeat.get('gaps')}",
            f"saved_at_ms: {heartbeat.get('saved_at_ms')}",
            "```",
            "",
        ]
    else:
        lines += [f"_No collector manifest: {forward.get('reason')}_", ""]

    lines += ["## STRATEGY LAB", ""]
    if lab["present"]:
        lifecycle = lab.get("lifecycle", {})
        lines += [
            "```text",
            "lifecycle     : "
            + " ".join(f"{key}={value}" for key, value in sorted(lifecycle.items())),
            f"paper-executable: {', '.join(lab.get('paper_executable') or []) or 'NONE'}",
            f"checks_ok     : {lab.get('all_checks_ok')}",
            "```",
            "",
        ]
    else:
        lines += [f"_No strategy lab report: {lab.get('reason')}_", ""]

    lines += ["## OPERATIONS", ""]
    operations = payload["operations"]
    disk_free = supervisor.get("disk_free_bytes")
    memory = supervisor.get("memory_mb")
    lines += [
        "```text",
        f"restarts    : {operations['restarts']}",
        f"crash loops : {operations['crash_loops']}",
        f"disk free   : {f'{disk_free / 1e9:.3f} GB' if disk_free is not None else 'n/a (no heartbeat)'}",
        f"memory      : {f'{memory} MB' if memory is not None else 'n/a (no heartbeat)'}",
        "```",
        "",
        f"_{operations['paper_and_collector_isolated']}_",
        "",
        f"_{operations['no_live_path']}_",
        "",
    ]
    if payload["honesty_notes"]:
        lines.append("## What this report does NOT claim")
        lines.append("")
        for note in payload["honesty_notes"]:
            lines.append(f"- {note}")
        lines.append("")
    if paper.get("strategy_attribution"):
        lines.append("## PAPER strategy attribution")
        lines.append("")
        for strategy_id, cell in sorted(paper["strategy_attribution"].items()):
            lines.append(f"- `{strategy_id}`: {cell}")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    args = parse_args()
    lab_run_dir = (REPO_ROOT / args.lab_run_dir).resolve()
    lab_run_dir.mkdir(parents=True, exist_ok=True)
    payload = build_report(args)
    stem = Path(args.out) if args.out else lab_run_dir / "SYSTEM_DAILY_REPORT"
    json_path = stem.with_suffix(".json")
    md_path = stem.with_suffix(".md")
    json_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    md_path.write_text(render_system_markdown(payload), encoding="utf-8")
    print(
        "[system] "
        + " ".join(f"{plane}={ok}" for plane, ok in payload["planes_present"].items())
    )
    print(f"[system] report: {json_path}")
    print(f"[system] report: {md_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
