"""edge14r_jesse_attempt — one bounded, honest attempt to run Jesse for real.

Jesse is installed in its own virtual environment outside this checkout and is
driven programmatically.  There is no attempt to make it work by weakening
anything: either its own engine runs a backtest on the same bars, or the exact
command, error, dependency and cause are recorded and the attempt is reported as
blocked.

Jesse 3.3.5 does not use Redis.  Its shared state is a bundled Rust coordinator
(``jesse_rust``) that the CLI starts before any work.  A first attempt that
called the backtest entrypoint directly therefore died on ``sync_redis is None``
— the module only binds a client when the working directory is a Jesse project
(``strategies/`` and ``storage/`` present), and nothing had started the
coordinator the client talks to.  This version performs the same bootstrap the
CLI performs, in-process, and then runs the engine:

    <jesse-venv>/python.exe scripts/edge14r_jesse_attempt.py --bars <path>

Nothing else is changed: the strategy, the fill timing, the commission and the
dataset are the frozen parity inputs.
"""

from __future__ import annotations

import argparse
import importlib
import json
import os
import sys
import time
import traceback
import uuid
from pathlib import Path
from typing import Any

STRATEGY_NAME = "NeutralMaCross"

STRATEGY_SOURCE = '''\
"""NEUTRAL_MA_CROSS_1H — the parity rule, transcribed into Jesse's vocabulary.

Long while ema(12) > ema(26) on the previous closed candle, flat otherwise. No
fitted parameter, one exit path, and the same fill timing the other engines are
given. Generated by scripts/edge14r_jesse_attempt.py.
"""

import numpy as np

from jesse.strategies import Strategy

# Diagnostic sink: Jesse keeps no strategy-side log for a silent research run, so
# the rule's own inputs are written next to the project while it executes. It is
# deleted once the attempt's evidence is written.
import json as _json
import os as _os


def _note(row: dict[str, Any]) -> None:
    try:
        path = _os.environ.get("EDGE14R_SIGNAL_LOG") or _os.path.join(_os.getcwd(), "signal_log.jsonl")
        with open(path, "a", encoding="utf-8") as fh:
            fh.write(_json.dumps(row) + "\\n")
    except Exception:
        pass


class NeutralMaCross(Strategy):
    def __init__(self) -> None:
        super().__init__()
        # The venue's commission, declared once and used to reserve room for it:
        # sizing the whole balance at ``self.balance / self.price`` leaves nothing
        # for the entry fee on a spot account and the engine rejects the order
        # with InsufficientBalance, which is a funding artefact and not a rule.
        self.fee_reserve = 0.001

    def _ema(self, period: int) -> float:
        closes = self.candles[:, 2]
        k = 2.0 / (period + 1.0)
        if len(closes) < period:
            return float("nan")
        value = float(np.mean(closes[:period]))
        for close in closes[period:]:
            value = float(close) * k + value * (1.0 - k)
        return value

    @property
    def ema_fast(self) -> float:
        return self._ema(12)

    @property
    def ema_slow(self) -> float:
        return self._ema(26)

    def should_long(self) -> bool:
        signal = self.ema_fast > self.ema_slow
        _note(
            {
                "hook": "should_long",
                "ts": int(self.current_candle[0]),
                "rows": int(self.candles.shape[0]),
                "fast": None if self.ema_fast != self.ema_fast else self.ema_fast,
                "slow": None if self.ema_slow != self.ema_slow else self.ema_slow,
                "signal": bool(signal),
                "price": float(self.price),
            }
        )
        return signal

    def should_short(self) -> bool:
        return False

    def go_long(self) -> None:
        qty = self.balance / (self.price * (1.0 + self.fee_reserve))
        _note(
            {
                "hook": "go_long",
                "ts": int(self.current_candle[0]),
                "balance": float(self.balance),
                "price": float(self.price),
                "qty": float(qty),
            }
        )
        self.buy = qty, self.price

    def should_cancel_entry(self) -> bool:
        return False

    def update_position(self) -> None:
        """The exit rule.

        Jesse 3.3.5 evaluates exits in ``update_position`` (there is no
        ``should_exit`` hook in this release: a strategy that defines one has a
        method the engine never calls), so the rule is expressed here and closes
        with the engine's own ``liquidate()``.
        """
        signal = self.ema_fast < self.ema_slow
        _note(
            {
                "hook": "update_position",
                "ts": int(self.current_candle[0]),
                "rows": int(self.candles.shape[0]),
                "fast": None if self.ema_fast != self.ema_fast else self.ema_fast,
                "slow": None if self.ema_slow != self.ema_slow else self.ema_slow,
                "signal": bool(signal),
                "price": float(self.price),
            }
        )
        if signal:
            self.liquidate()
'''


def _bars_to_jesse(bars_path: Path, symbols: list[str], exchange: str) -> dict[str, Any]:
    """Shape the frozen dataset the way Jesse's backtest accepts it in memory.

    The shape is the one ``backtest_mode.load_candles`` itself builds: a dict keyed
    by ``{exchange}-{symbol}`` whose values carry the NumPy candle array.  Passing
    the candles in removes the one dependency that cannot be created here — a
    database of imported candles — without inventing anything: the rows are the
    same rows the other engines were given.
    """
    import numpy as np

    by_symbol: dict[str, list[list[float]]] = {}
    for line in bars_path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        base = str(row["symbol"]).replace("-", "/")
        if base not in symbols:
            continue
        # Jesse's row order is [timestamp, open, close, high, low, volume]
        # (its own frontend formatter reads c[2] as close and c[3]/c[4] as
        # high/low), while the dataset is written in the usual OHLC order.  The
        # two are transposed here deliberately: handing over the OHLC order made
        # the engine's "close" the bar's high, which produced one trade in a
        # 40-day window and looked like a rule disagreement.
        by_symbol.setdefault(base, []).append(
            [
                int(row["timestamp"]),
                float(row["open"]),
                float(row["close"]),
                float(row["high"]),
                float(row["low"]),
                float(row["volume"]),
            ]
        )
    shaped: dict[str, dict[str, Any]] = {}
    for symbol, rows in sorted(by_symbol.items()):
        jesse_symbol = symbol.replace("/", "-")
        shaped[f"{exchange}-{jesse_symbol}"] = {
            "exchange": exchange,
            "symbol": jesse_symbol,
            "candles": np.asarray(rows, dtype="float64"),
        }
    return shaped


def _iso(ms: int) -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(ms / 1000))


def _collect_trades() -> list[dict[str, Any]]:
    """Read the completed trades the engine itself produced, from its own store.

    Jesse 3.x keeps closed trades on ``store.closed_trades.trades`` (the
    ``ClosedTrade`` instances the engine finalized); the older
    ``store.completed_trades`` name does not exist in this release.
    """
    from jesse.store import store  # type: ignore[import-not-found]

    rows: list[dict[str, Any]] = []
    closed = store.closed_trades.trades
    for trade in list(closed):
        rows.append(
            {
                "symbol": str(getattr(trade, "symbol", "")),
                "exchange": str(getattr(trade, "exchange", "")),
                "type": str(getattr(trade, "type", "")),
                "opened_at": int(getattr(trade, "opened_at", 0) or 0),
                "closed_at": int(getattr(trade, "closed_at", 0) or 0),
                "entry_price": float(getattr(trade, "entry_price", 0.0) or 0.0),
                "exit_price": float(getattr(trade, "exit_price", 0.0) or 0.0),
                "qty": float(getattr(trade, "qty", 0.0) or 0.0),
                "fee": float(getattr(trade, "fee", 0.0) or 0.0),
                "size": float(getattr(trade, "size", 0.0) or 0.0),
                "pnl": float(getattr(trade, "pnl", 0.0) or 0.0),
                "holding_period": int(getattr(trade, "holding_period", 0) or 0),
            }
        )
    return rows


def main() -> int:
    parser = argparse.ArgumentParser(description="WP-EDGE-14R Jesse attempt")
    parser.add_argument("--bars", required=True)
    parser.add_argument("--symbols", default="BTC/USDT,ETH/USDT")
    parser.add_argument("--balance", type=float, default=10_000.0)
    parser.add_argument("--fee", type=float, default=0.001)
    parser.add_argument("--exchange-type", default="spot", choices=["spot", "futures"])
    parser.add_argument("--exchange-name", default="Binance")
    parser.add_argument(
        "--client-id",
        default=str(uuid.uuid4()),
        help="Jesse keys a session by UUID; a free-form id is rejected by its own session table",
    )
    parser.add_argument("--out", default="jesse_attempt.json")
    args = parser.parse_args()

    record: dict[str, Any] = {
        "engine": "jesse",
        "attempted_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "inside_repository_tree": False,
        "order_sent": False,
        "credentials_used": False,
        "bootstrap": "coordination_runtime.start(owner client) — the same call the jesse CLI makes",
        "history": [
            {
                "attempt": 1,
                "what": "called jesse.modes.backtest_mode.run directly with candles in memory",
                "outcome": "BLOCKED",
                "stage": "run",
                "error_type": "AttributeError",
                "error": "'NoneType' object has no attribute 'sismember'",
                "cause": (
                    "no Jesse project (strategies/ + storage/) existed, so jesse.services.redis "
                    "bound no client and the bundled Rust coordinator was never started"
                ),
            }
        ],
    }
    try:
        import importlib.metadata as md

        record["version"] = md.version("jesse")
    except Exception as exc:  # pragma: no cover - version reporting is best effort
        record["version"] = f"unknown ({exc})"

    workspace = Path.cwd()
    strategies_dir = workspace / "strategies" / STRATEGY_NAME
    strategies_dir.mkdir(parents=True, exist_ok=True)
    (strategies_dir / "__init__.py").write_text(STRATEGY_SOURCE, encoding="utf-8")
    (workspace / "storage").mkdir(exist_ok=True)

    symbols = [s.strip() for s in args.symbols.split(",") if s.strip()]
    jesse_symbols = [s.replace("/", "-") for s in symbols]
    try:
        candles = _bars_to_jesse(Path(args.bars), symbols, args.exchange_name)
    except Exception as exc:
        record.update({"outcome": "BLOCKED", "stage": "candles", "error": repr(exc)})
        Path(args.out).write_text(json.dumps(record, indent=2), encoding="utf-8")
        print(json.dumps(record, indent=2))
        return 1

    record["candles"] = {
        key: {"shaped": True, "rows": int(series["candles"].shape[0])}
        for key, series in candles.items()
    }
    if not candles:
        record.update(
            {"outcome": "BLOCKED", "stage": "candles", "error": "no symbol in the dataset matched"}
        )
        Path(args.out).write_text(json.dumps(record, indent=2), encoding="utf-8")
        print(json.dumps(record, indent=2))
        return 1

    starts = [int(series["candles"][0][0]) for series in candles.values()]
    ends = [int(series["candles"][-1][0]) for series in candles.values()]
    start = time.strftime("%Y-%m-%d", time.gmtime(min(starts) / 1000))
    finish = time.strftime("%Y-%m-%d", time.gmtime(max(ends) / 1000))
    record["window"] = {"start_date": start, "finish_date": finish}

    # --- bootstrap: exactly what `jesse run` does before it accepts work -------
    try:
        import jesse.helpers as jh  # type: ignore[import-not-found]
        from jesse.services import coordination_runtime  # type: ignore[import-not-found]
        from jesse.services.env import ENV_VALUES  # type: ignore[import-not-found]

        if not jh.is_jesse_project():
            raise RuntimeError("cwd is not a Jesse project (strategies/ + storage/)")
        owner = coordination_runtime.create_client(ENV_VALUES, owner=True)
        coordination_runtime.start(owner)
        from jesse.services.redis import (  # type: ignore[import-not-found]
            is_process_active,
            sync_redis,
        )

        active_key = f"{ENV_VALUES['APP_PORT']}|active-processes"
        sync_redis.sadd(active_key, args.client_id)
        record["coordinator"] = {
            "bootstrap_ok": True,
            "app_port": str(ENV_VALUES.get("APP_PORT")),
            "client_registered_active": bool(is_process_active(args.client_id)),
        }
    except Exception as exc:
        record.update(
            {
                "outcome": "BLOCKED",
                "stage": "bootstrap",
                "error_type": type(exc).__name__,
                "error": str(exc)[:2000],
                "dependency": "jesse_rust (bundled Rust coordinator)",
                "traceback_tail": traceback.format_exc()[-3000:],
            }
        )
        Path(args.out).write_text(json.dumps(record, indent=2, default=str), encoding="utf-8")
        print(
            json.dumps({k: v for k, v in record.items() if k != "traceback_tail"}, indent=2)[:4000]
        )
        return 1

    routes = [
        {
            "exchange": args.exchange_name,
            "strategy": STRATEGY_NAME,
            "symbol": s,
            "timeframe": "1h",
        }
        for s in jesse_symbols
    ]
    # Jesse's own set_config() reads the dashboard-shaped config: the fee, the
    # balance and the market type live under the exchange entry, not at the top
    # level.  Passing the dashboard shape is what keeps this a stock run.
    user_config = {
        "warm_up_candles": 0,
        "logging": {
            "strategy_execution": True,
            "order_submission": True,
            "order_cancellation": True,
            "order_execution": True,
            "position_opened": True,
            "position_increased": True,
            "position_reduced": True,
            "position_closed": True,
            "shorter_period_candles": False,
            "trading_candles": True,
            "balance_update": True,
            "exchange_ws_reconnection": True,
        },
        "exchanges": {
            "Binance": {
                "fee": args.fee,
                "type": args.exchange_type,
                "balance": args.balance,
                "futures_leverage": 1,
                "futures_leverage_mode": "cross",
            }
        },
    }
    record["invocation"] = {
        "entrypoint": "jesse.modes.backtest_mode.run",
        "routes": routes,
        "start_date": start,
        "finish_date": finish,
        "candles_passed_in_memory": True,
        "user_config": user_config,
        # One route per run.  A single run with both routes shares one spot
        # balance, so the first symbol's 100%-of-equity entry leaves the second
        # with nothing and its order is rejected (`qty cannot be 0`) — a shared
        # wallet artefact, not a rule disagreement.  The other engines are given
        # one independent account per symbol; running one route at a time is the
        # same convention rather than a different one.
        "one_route_per_run": True,
    }

    # Resolve the strategy the way Jesse will (pydoc.locate on `strategies.X.X`),
    # and say where it resolved from: a silent miss there is a run with no rules.
    if str(workspace) not in sys.path:
        sys.path.insert(0, str(workspace))
    try:
        record["strategy_module_file"] = getattr(
            importlib.import_module(f"strategies.{STRATEGY_NAME}"), "__file__", None
        )
    except Exception as exc:
        record["strategy_module_error"] = repr(exc)

    signal_log = workspace / "signal_log.jsonl"
    signal_log.unlink(missing_ok=True)
    os.environ["EDGE14R_SIGNAL_LOG"] = str(signal_log)
    record["signal_log"] = str(signal_log)
    runs: list[dict[str, Any]] = []
    trades: list[dict[str, Any]] = []
    try:
        from jesse.modes.backtest_mode import (  # type: ignore[import-not-found]
            run as jesse_backtest,
        )
        from jesse.services.redis import sync_redis

        for symbol in jesse_symbols:
            run_client_id = str(uuid.uuid4())
            sync_redis.sadd(f"{ENV_VALUES['APP_PORT']}|active-processes", run_client_id)
            start_time = time.time()
            jesse_backtest(
                client_id=run_client_id,
                debug_mode=False,
                user_config=user_config,
                exchange=args.exchange_name,
                routes=[
                    {
                        "exchange": args.exchange_name,
                        "strategy": STRATEGY_NAME,
                        "symbol": symbol,
                        "timeframe": "1h",
                    }
                ],
                data_routes=[{"exchange": args.exchange_name, "symbol": symbol, "timeframe": "1h"}],
                start_date=start,
                finish_date=finish,
                candles={k: v for k, v in candles.items() if k.endswith(symbol)},
                # the engine's own export: it writes storage/json/<session>.json
                # from store.closed_trades before the run tears its state down,
                # so trades are read back from Jesse's file rather than a hook
                json=True,
                csv=True,
            )
            exported = workspace / "storage" / "json" / f"{run_client_id}.json"
            symbol_trades: list[dict[str, Any]] = []
            if exported.is_file():
                payload = json.loads(exported.read_text(encoding="utf-8"))
                symbol_trades = list(payload.get("trades") or [])
            runs.append(
                {
                    "symbol": symbol,
                    "client_id": run_client_id,
                    "export": str(exported),
                    "trades": len(symbol_trades),
                    "duration_seconds": round(time.time() - start_time, 2),
                }
            )
            trades.extend(symbol_trades)
        record["outcome"] = "EXECUTED"
    except BaseException as exc:
        record.update(
            {
                "outcome": "BLOCKED",
                "stage": "run",
                "error_type": type(exc).__name__,
                "error": str(exc)[:2000],
                "traceback_tail": traceback.format_exc()[-4000:],
            }
        )
    finally:
        record["runs"] = runs
        # The engine exports its own closed trades during the run; that file is
        # read first because the run tears its in-memory state down afterwards.
        record["engine_export_trades"] = len(trades)
        if not trades:
            try:
                trades = _collect_trades()
            except Exception as exc:  # pragma: no cover - the store is best effort
                record["trade_collection_error"] = repr(exc)

    if signal_log.is_file():
        lines = signal_log.read_text(encoding="utf-8").splitlines()
        longs = sum(1 for line in lines if '"signal": true' in line)
        record["strategy_executions"] = len(lines)
        record["long_signals"] = longs
    else:
        record["strategy_executions"] = 0
        record["long_signals"] = 0
    record["trades"] = trades
    record["n_trades"] = len(trades)
    if trades and record.get("outcome") != "EXECUTED":
        # The engine simulated and then failed on its own session persistence; the
        # fills are still its fills, and the record must say exactly that.
        record["outcome"] = "EXECUTED_WITH_POST_RUN_FAILURE"
    Path(args.out).write_text(json.dumps(record, indent=2, default=str), encoding="utf-8")
    print(
        json.dumps(
            {k: v for k, v in record.items() if k not in ("traceback_tail", "trades")}, indent=2
        )[:4000]
    )
    return 0 if record.get("outcome", "").startswith("EXECUTED") else 1


if __name__ == "__main__":
    sys.exit(main())
