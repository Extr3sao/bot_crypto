def now_ms() -> int:
    return int(datetime.now(tz=UTC).timestamp() * 1000)


def stamp(instant_ms: int) -> str:
    return datetime.fromtimestamp(instant_ms / 1000, tz=UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def tree_scan(root: Path) -> dict[str, Any]:
    """One walk of a subtree: bytes, files, and a digest of the listing itself.

    The digest is over ``(relative path, size)`` pairs in sorted order.  It is not a
    hash of the content — that would cost another full read of 5 GiB to say what the
    listing already says — it is a receipt for *this* inventory: re-run the walk and an
    unchanged tree reproduces the digest, a tree that moved shows up as a different one.
    """
    total = 0
    files = 0
    listing = hashlib.sha256()
    largest: list[tuple[int, str]] = []
    for dirpath, dirnames, filenames in os.walk(root, onerror=lambda _e: None):
        dirnames.sort()
        for name in sorted(filenames):
            path = Path(dirpath) / name
            try:
                size = path.stat().st_size
            except OSError:
                continue
            total += size
            files += 1
            rel = path.relative_to(root).as_posix()
            listing.update(f"{rel}\0{size}\n".encode("utf-8"))
            largest.append((size, rel))
    largest.sort(reverse=True)
    return {
        "bytes": total,
        "files": files,
        "tree_digest": listing.hexdigest(),
        "largest": largest[:8],
    }


def owner_of(relative_path: str) -> tuple[str, str]:
    """``(owner, basis)`` for a repository-relative path. Never guesses: says so."""
    posix = relative_path.replace("\\", "/").strip("/")
    for prefix, owner in KNOWN_WORKSTREAMS:
        if posix == prefix or posix.startswith(prefix + "/"):
            return owner, f"path prefix {prefix!r}"
    head = posix.split("/", 1)[0]
    if head in {p for p, _ in KNOWN_WORKSTREAMS}:
        return f"unattributed ({head})", "top-level path prefix only"
    return "UNATTRIBUTED", "no rule matched"


#: Kinds of bytes that belong to no workstream: git wrote one, the interpreter wrote
#: another, a tool wrote the third. Saying "unattributed" about them would suggest a
#: workstream that forgot to claim them, which is not what is going on.
NOT_A_WORKSTREAM = {"VERSION_HISTORY", "ENVIRONMENT", "TOOL_CACHE"}


def attribution(relative_path: str, category: str, *, broke_down: bool) -> tuple[str, str]:
    """Who owns a **top-level** row, and on what basis."""
    if category in NOT_A_WORKSTREAM:
        return "n/a — not a workstream", "a kind of bytes, not an owner"
    if broke_down:
        return "mixed — see the breakdown", "its children are attributed one by one below"
    owner, basis = owner_of(relative_path)
    if owner == "UNATTRIBUTED":
        return "repository tooling", "a repository file, not a workstream's artefact"
    return owner, basis


def category_of(name: str) -> str:
    if name in CATEGORY_BY_NAME:
        return CATEGORY_BY_NAME[name]
    if name in CACHE_DIR_NAMES or any(
        name == cache or (cache.endswith("*") and name.startswith(cache[:-1]))
        for cache in CACHE_FILE_NAMES
    ):
        return "TOOL_CACHE"
    return "UNCLASSIFIED"


def cache_paths(root: Path) -> list[Path]:
    """Every tool cache under ``root``, directories and files alike."""
    found: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(root, onerror=lambda _e: None):
        if Path(dirpath).name == ".git":
            dirnames[:] = []
            continue
        for name in list(dirnames):
            if name in CACHE_DIR_NAMES:
                found.append(Path(dirpath) / name)
                dirnames.remove(name)  # nothing inside it is enumerated separately
        for name in filenames:
            if name == ".coverage" or name.startswith(".coverage."):
                found.append(Path(dirpath) / name)
    return sorted(found)


def tracked_paths(root: Path) -> set[str]:
    """The repository-relative paths git tracks, as a set, or an empty set with a note."""
    import subprocess

    try:
        result = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z"],
            capture_output=True,
            check=False,
        )
    except OSError:
        return set()
    if result.returncode != 0:
        return set()
    return {
        item.decode("utf-8", "replace").replace("\\", "/")
        for item in result.stdout.split(b"\0")
        if item
    }


def ignored_by_gitignore(root: Path, paths: list[Path]) -> dict[str, bool]:
    """Ask git which of ``paths`` it ignores. ``check-ignore`` is the authority, not us."""
    import subprocess

    verdict: dict[str, bool] = {}
    for path in paths:
        try:
            rel = path.relative_to(root).as_posix()
        except ValueError:
            rel = path.as_posix()
        result = subprocess.run(
            ["git", "-C", str(root), "check-ignore", "--quiet", rel],
            capture_output=True,
            check=False,
        )
        verdict[rel] = result.returncode == 0
    return verdict


def file_size_tree(path: Path) -> tuple[int, int]:
    if path.is_file():
        try:
            return path.stat().st_size, 1
        except OSError:
            return 0, 0
    scan = tree_scan(path)
    return int(scan["bytes"]), int(scan["files"])


def figure(
    *,
    name: str,
    value: Any,
    unit: str,
    as_of_utc: str,
    source_artifact: str,
    source_digest: str,
    measurement_scope: str,
    note: str = "",
) -> dict[str, Any]:
    """One number with the instant it was read at and the artefact it came from."""
    return {
        "figure": name,
        "value": value,
        "unit": unit,
        "run_id": f"EDGE05R-STORE-{as_of_utc.replace('-', '').replace(':', '')}",
        "as_of_utc": as_of_utc,
        "source_artifact": source_artifact,
        "source_digest": source_digest,
        "measurement_scope": measurement_scope,
        "note": note,
    }


def build(root: Path, *, top_largest: int = 20) -> dict[str, Any]:
    instant = now_ms()
    as_of = stamp(instant)
    volume = shutil.disk_usage(root)

    entries: list[dict[str, Any]] = []
    for entry in sorted(os.scandir(root), key=lambda item: item.name):
        try:
            size, files = file_size_tree(Path(entry.path))
        except OSError:
            continue
        if entry.is_dir(follow_symlinks=False):
            scan = tree_scan(Path(entry.path))
            digest = str(scan["tree_digest"])
            largest = scan["largest"]
        else:
            digest = sha256_file(Path(entry.path)) if size else ""
            largest = []
        family = (
            entry.is_dir(follow_symlinks=False)
            and entry.name in BREAKDOWN_NAMES
        )
        owner, basis = attribution(entry.name, category_of(entry.name), broke_down=family)
        entries.append(
            {
                "path": entry.name + ("/" if entry.is_dir(follow_symlinks=False) else ""),
                "bytes": size,
                "files": files,
                "category": category_of(entry.name),
                "owner": owner,
                "owner_basis": basis,
                "tree_digest": digest,
                "largest_members": [
                    {"bytes": item_size, "path": item_rel} for item_size, item_rel in largest
                ],
            }
        )
    entries.sort(key=lambda row: -int(row["bytes"]))

    # `data/` and `reports/` hold both this chain's bytes and other workstreams'. The
    # top-level row cannot say which, so each is broken down one level.
    breakdown: dict[str, list[dict[str, Any]]] = {}
    for name in BREAKDOWN_NAMES:
        base = root / name
        if not base.is_dir():
            continue
        rows = []
        for child in sorted(os.scandir(base), key=lambda item: item.name):
            size, files = file_size_tree(Path(child.path))
            rel = f"{name}/{child.name}"
            owner, basis = owner_of(rel)
            rows.append(
                {
                    "path": rel + ("/" if child.is_dir(follow_symlinks=False) else ""),
                    "bytes": size,
                    "files": files,
                    "owner": owner,
                    "owner_basis": basis,
                }
            )
        breakdown[name] = sorted(rows, key=lambda row: -int(row["bytes"]))

    # Largest individual files in the repository, this chain's and everybody's.
    biggest: list[tuple[int, str]] = []
    for dirpath, dirnames, filenames in os.walk(root, onerror=lambda _e: None):
        if Path(dirpath).name == ".git":
            dirnames[:] = []
            continue
        for name in filenames:
            path = Path(dirpath) / name
            try:
                biggest.append((path.stat().st_size, path.relative_to(root).as_posix()))
            except OSError:
                continue
    biggest.sort(reverse=True)

    repo_bytes = sum(int(row["bytes"]) for row in entries)

    # ---- the reclaim plan: what a strictly-safe cleanup would return, and the proof --
    caches = cache_paths(root)
    tracked = tracked_paths(root)
    ignored = ignored_by_gitignore(root, caches)
    plan_rows: list[dict[str, Any]] = []
    reclaimable = 0
    by_scope: dict[str, int] = {}
    for path in caches:
        rel = path.relative_to(root).as_posix()
        size, files = file_size_tree(path)
        tracked_here = [t for t in tracked if t == rel or t.startswith(rel + "/")]
        scope = (
            "interpreter bytecode inside the project environment"
            if rel.startswith(".venv/")
            else "repository tool cache"
        )
        plan_rows.append(
            {
                "path": rel,
                "bytes": size,
                "files": files,
                "scope": scope,
                "regenerable": True,
                "regenerated_by": (
                    "python (bytecode cache)"
                    if path.name == "__pycache__"
                    else path.name.strip(".").split("_")[0]
                ),
                "tracked_by_git": bool(tracked_here),
                "ignored_by_gitignore": bool(ignored.get(rel, False)),
                "safe_to_reclaim": (not tracked_here) and bool(ignored.get(rel, False)),
                "basis": (
                    "the tool that wrote it regenerates it; git tracks none of it and "
                    ".gitignore names it"
                ),
            }
        )
        if plan_rows[-1]["safe_to_reclaim"]:
            reclaimable += size
            by_scope[scope] = by_scope.get(scope, 0) + size
    plan_rows.sort(key=lambda row: -int(row["bytes"]))

    payload: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "run_id": f"EDGE05R-STORE-{as_of.replace('-', '').replace(':', '')}",
        "generated_at_utc": as_of,
        "as_of_utc": as_of,
        "host": os.environ.get("COMPUTERNAME", "unknown"),
        "repo_root": str(root),
        "volume": {
            "anchor": str(root),
            "drive": root.drive,
            "free_bytes": volume.free,
            "total_bytes": volume.total,
            "used_bytes": volume.used,
            "used_percent": round(volume.used / volume.total * 100, 2),
            "free_gib": round(volume.free / GIB, 3),
            "critical_floor_bytes": 2 * GIB,
            "healthy_floor_bytes": 5 * GIB,
            "reading": (
                "free space is a property of the volume, so it is measured at the "
                "repository root; the floors are the ones the lane's own guard declares"
            ),
        },
        "totals": {
            "repo_bytes": repo_bytes,
            "repo_files": sum(int(row["files"]) for row in entries),
            "repo_gib": round(repo_bytes / GIB, 3),
            "share_of_volume": round(repo_bytes / volume.total * 100, 2),
        },
        "subtrees": entries,
        "breakdown": breakdown,
        "largest_files": [
            {"bytes": size, "path": rel, "owner": owner_of(rel)[0]}
            for size, rel in biggest[:top_largest]
        ],
        "reclaim_plan": {
            "rule": (
                "only a tool cache a tool regenerates, that git does not track and that "
                ".gitignore names; every row carries its own three checks"
            ),
            "paths": plan_rows,
            "safe_reclaimable_bytes": reclaimable,
            "safe_reclaimable_mib": round(reclaimable / MIB, 2),
            "safe_reclaimable_by_scope": {
                scope: {"bytes": value, "mib": round(value / MIB, 2)}
                for scope, value in sorted(by_scope.items())
            },
            "nothing_else_is_proposed": (
                "market data, evidence, other workstreams' artefacts, source and the "
                "environment are sized here and left alone: deleting them is a decision "
                "for the owner, not a cleanup"
            ),
        },
        "hypothetical": True,
        "order_sent": False,
        "promotion": "NONE",
    }

    payload["figures"] = [
        figure(
            name="volume_free_bytes",
            value=volume.free,
            unit="bytes",
            as_of_utc=as_of,
            source_artifact="operating system, disk_usage of the repository volume",
            source_digest=hashlib.sha256(f"{volume.free}:{volume.total}".encode()).hexdigest(),
            measurement_scope=f"volume {root.drive} as seen from {root}",
        ),
        figure(
            name="repo_bytes",
            value=repo_bytes,
            unit="bytes",
            as_of_utc=as_of,
            source_artifact="repository tree walk (this script)",
            source_digest=hashlib.sha256(
                json.dumps(
                    [{"p": r["path"], "d": r["tree_digest"]} for r in entries],
                    sort_keys=True,
                ).encode()
            ).hexdigest(),
            measurement_scope="every file under the repository root, excluding .git internals",
        ),
        figure(
            name="safe_reclaimable_bytes",
            value=reclaimable,
            unit="bytes",
            as_of_utc=as_of,
            source_artifact="git check-ignore + git ls-files + a walk for cache names",
            source_digest=hashlib.sha256(
                json.dumps(
                    [{"p": r["path"], "b": r["bytes"]} for r in plan_rows], sort_keys=True
                ).encode()
            ).hexdigest(),
            measurement_scope="tool caches only, each verified untracked and ignored",
        ),
    ]
    return payload


def render(payload: dict[str, Any]) -> str:
    volume = payload["volume"]
    totals = payload["totals"]
    lines = [
        f"# {payload.get('label', DEFAULT_LABEL)} — storage diagnosis: where the volume went, "
        "and what is mine to move",
        "",
        f"*Read at `{payload['as_of_utc']}` on `{payload['host']}`. Read-only: this file "
        "sizes things and says who owns them; it deletes nothing.*",
        "",
        "## 1. The volume",
        "",
        "| | |",
        "| --- | --- |",
        f"| Volume | `{volume['drive']}` |",
        f"| Free | **{volume['free_gib']} GiB** ({volume['free_bytes']} bytes) |",
        f"| Total | {volume['total_bytes']} bytes ({round(volume['total_bytes'] / GIB, 1)} GiB) |",
        f"| Used | {volume['used_percent']} % |",
        f"| Critical floor (the lane's own) | {volume['critical_floor_bytes']} bytes (2 GiB) |",
        f"| Healthy floor (the lane's own) | {volume['healthy_floor_bytes']} bytes (5 GiB) |",
        "",
        f"This repository is **{totals['repo_gib']} GiB** "
        f"({totals['repo_bytes']} bytes, {totals['repo_files']} files), which is "
        f"**{totals['share_of_volume']} %** of the volume. The rest of the {round(volume['total_bytes'] / GIB, 1)} GiB "
        "is outside this repository and outside this workstream's authority: it is not "
        "touched, not measured further, and only named as context for the owner.",
        "",
        "## 2. Every top-level subtree, by kind of bytes and by owner",
        "",
        "| Path | Size | Files | Kind | Owner | Basis of the attribution |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for row in payload["subtrees"]:
        lines.append(
            f"| `{row['path']}` | {row['bytes'] / MIB:,.1f} MiB | {row['files']} | "
            f"{row['category']} | {row['owner']} | {row['owner_basis']} |"
        )
    lines += [
        "",
        "> An owner is stated from a **path prefix**, and the basis is printed next to it. "
        "Where no rule matches, the row says `UNATTRIBUTED` rather than inventing an owner.",
        "",
    ]

    for name, rows in payload["breakdown"].items():
        lines += [
            f"### `{name}/`, one level down",
            "",
            "| Path | Size | Files | Owner | Basis |",
            "| --- | --- | --- | --- | --- |",
        ]
        for row in rows:
            lines.append(
                f"| `{row['path']}` | {row['bytes'] / MIB:,.1f} MiB | {row['files']} | "
                f"{row['owner']} | {row['owner_basis']} |"
            )
        lines.append("")

    lines += [
        "## 3. The largest individual files",
        "",
        "| Size | Path | Owner |",
        "| --- | --- | --- |",
    ]
    for row in payload["largest_files"]:
        lines.append(f"| {row['bytes'] / MIB:,.2f} MiB | `{row['path']}` | {row['owner']} |")

    plan = payload["reclaim_plan"]
    lines += [
        "",
        "## 4. The reclaim plan, and the proof behind every row",
        "",
        f"Rule: {plan['rule']}.",
        "",
        f"**Safe to reclaim: {plan['safe_reclaimable_mib']} MiB "
        f"({plan['safe_reclaimable_bytes']} bytes).**",
        "",
    ]
    for scope, body in (plan.get("safe_reclaimable_by_scope") or {}).items():
        lines.append(f"* {body['mib']:,.2f} MiB — {scope}")
    lines += [
        "",
        "| Path | Size | Scope | Regenerated by | Tracked by git | Ignored | Safe |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in plan["paths"][:40]:
        lines.append(
            f"| `{row['path']}` | {row['bytes'] / 1024:,.1f} KiB | {row.get('scope', '')} | "
            f"{row['regenerated_by']} | {row['tracked_by_git']} | {row['ignored_by_gitignore']} | "
            f"{row['safe_to_reclaim']} |"
        )
    if len(plan["paths"]) > 40:
        lines.append(
            f"| *({len(plan['paths']) - 40} more rows in the JSON)* | | | | | | |"
        )
    lines += [
        "",
        plan["nothing_else_is_proposed"] + ".",
        "",
        "## 5. Every figure above, with the instant it was read at",
        "",
        "| Figure | Value | Unit | as_of_utc | Source artefact | Source digest | Scope |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in payload["figures"]:
        lines.append(
            f"| `{row['figure']}` | {row['value']} | {row['unit']} | {row['as_of_utc']} | "
            f"{row['source_artifact']} | `{row['source_digest'][:16]}…` | "
            f"{row['measurement_scope']} |"
        )
    lines += [
        "",
        f"*`run_id` for every figure in this file: `{payload['run_id']}`. Two figures with "
        "different `as_of_utc` are two readings of a moving system, never one total.*",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--root", default=None, help="repository root to inventory")
    parser.add_argument("--out", default=None, help="directory for the two artefacts")
    parser.add_argument("--top", type=int, default=20, help="how many largest files to list")
    parser.add_argument("--json", action="store_true", help="print the payload, write nothing")
    #: The work package that is RE-RUNNING this tool, not the one that wrote it: the same
    #: measurement taken later belongs to the later reading, and a file titled with the
    #: earlier one invites a reader to date the numbers by their heading.
    parser.add_argument("--label", default=DEFAULT_LABEL)
    options = parser.parse_args(argv)

    root = Path(options.root).resolve() if options.root else REPO_ROOT
    out = (
        Path(options.out)
        if options.out
        else REPO_ROOT / "reports" / "edge-recovery" / "WP-EDGE-05R"
    )
    payload = build(root, top_largest=options.top)
    payload["label"] = options.label

    if options.json:
        print(json.dumps(payload, indent=2, sort_keys=True, default=str))
        return 0

    out.mkdir(parents=True, exist_ok=True)
    (out / "STORAGE_INVENTORY.json").write_text(
        json.dumps(payload, indent=2, sort_keys=True, default=str) + "\n", encoding="utf-8"
    )
    (out / "STORAGE_INVENTORY.md").write_text(render(payload), encoding="utf-8")
    print(f"free {payload['volume']['free_gib']} GiB of a {round(payload['volume']['total_bytes'] / GIB, 1)} GiB volume")
    print(f"repository {payload['totals']['repo_gib']} GiB in {payload['totals']['repo_files']} files")
    print(f"safe to reclaim {payload['reclaim_plan']['safe_reclaimable_mib']} MiB")
    print(f"wrote STORAGE_INVENTORY.json and STORAGE_INVENTORY.md into {out}")
    return 0


