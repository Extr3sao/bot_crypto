#!/usr/bin/env python
"""WP-EDGE-05R — where the volume went, who owns it, and what could safely come back.

Read-only. It answers three questions and refuses to answer any fourth:

1. How much free space does the volume hold, and how much of it is this repository?
2. Every top-level subtree, sized, classified by *kind* of bytes (version history,
   environment, market data, evidence, source, logs, tool cache) and attributed to the
   workstream whose path prefix owns it — with the basis of that attribution stated, so a
   reader can disagree with it.
3. Which bytes are *demonstrably* safe to reclaim, and why: the tool caches a tool
   regenerates, that git does not track and that `.gitignore` names.  Everything else is
   reported as evidence or as somebody else's, and is never proposed for deletion here.

The distinction that matters is between "large" and "mine to delete".  Nearly all of the
repository's bytes are evidence written by other workstreams; this script sizes them and
says so, so that the only thing that moves is what the proof covers.

Every figure it prints is also emitted with its provenance — `run_id`, `as_of_utc`,
`source_artifact`, `source_digest`, `measurement_scope` — because a number without the
instant it was read at is a number that silently goes stale.
"""

from __future__ import annotations

