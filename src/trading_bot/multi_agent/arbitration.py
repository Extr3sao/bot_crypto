@dataclass(frozen=True, slots=True)
class GroupVerification:
    """Immutable result of independent OpportunityGroup verification."""

    group_id: str
    verdict: GroupVerificationStatus
    checks: tuple[tuple[str, str, str], ...]

    @property
    def passed(self) -> bool:
        return self.verdict is GroupVerificationStatus.VERIFIED

    def to_dict(self) -> dict[str, Any]:
        return {
            "group_id": self.group_id,
            "verdict": self.verdict.value,
            "checks": [[name, status, detail] for name, status, detail in self.checks],
        }


class OpportunityGroupVerifier:
    """Independent deterministic verification of an OpportunityGroup.

    Not the arbiter: this class re-derives every claim from the authoritative
    proposals/evidence and compares. A forged score, a stripped losing side,
    a foreign-run candidate, or future-dated evidence fails verification.
    """

    version = GROUP_VERIFIER_VERSION

    def __init__(self, *, min_direction_score: float = 0.0) -> None:
        self.min_direction_score = min_direction_score

    def verify(
        self,
        group: OpportunityGroup,
        *,
        proposals: Mapping[str, TradeProposal],
        evidence_registry: Mapping[str, Any],
        assessments: Mapping[str, Any] | None = None,
        now: datetime | None = None,
    ) -> GroupVerification:
        checks: list[tuple[str, str, str]] = []

        def record(name: str, ok: bool, detail: str = "") -> None:
            checks.append((name, "PASS" if ok else "FAIL", detail))

        arbiter = DirectionArbiter(min_direction_score=self.min_direction_score)

        # Run authority.
        refs = [ref for ref in (group.long_candidate_ref, group.short_candidate_ref) if ref]
        foreign = sorted(
            ref for ref in refs if ref not in proposals or proposals[ref].run_id != group.run_id
        )
        record("run_authority_candidates", not foreign, f"foreign={foreign}")

        # Candidate binding: refs resolve and match group identity.
        binding_bad: list[str] = []
        for ref in refs:
            proposal = proposals.get(ref)
            if proposal is None:
                binding_bad.append(f"{ref}:missing")
                continue
            if (
                proposal.asset != group.asset
                or proposal.strategy != group.strategy
                or proposal.timeframe != group.timeframe
                or proposal.trace_id != group.trace_id
            ):
                binding_bad.append(f"{ref}:identity-mismatch")
            if proposal.direction.value != (
                SELECTED_LONG if ref == group.long_candidate_ref else SELECTED_SHORT
            ):
                binding_bad.append(f"{ref}:direction-mismatch")
        record("candidate_binding", not binding_bad, f"violations={binding_bad}")

        # No stripping: both sides that existed must still be recorded.
        present_long = any(
            item.direction == SELECTED_LONG for item in group.direction_scores
        )
        present_short = any(
            item.direction == SELECTED_SHORT for item in group.direction_scores
        )
        stripping = (
            (group.long_candidate_ref is not None and not present_long)
            or (group.short_candidate_ref is not None and not present_short)
            or (group.long_candidate_ref is None and present_long)
            or (group.short_candidate_ref is None and present_short)
        )
        record(
            "losing_direction_preserved",
            not stripping,
            f"long={group.long_candidate_ref} short={group.short_candidate_ref}",
        )

        # Direction score integrity: re-derive with the same deterministic rule.
        score_bad: list[str] = []
        for recorded in group.direction_scores:
            proposal = proposals.get(recorded.proposal_ref)
            if proposal is None:
                score_bad.append(f"{recorded.proposal_ref}:missing")
                continue
            assessment = (assessments or {}).get(proposal.asset)
            rederived = arbiter._score(proposal, evidence_registry, assessment, None)
            if (
                rederived.score != recorded.score
                or rederived.score_components != recorded.score_components
                or rederived.evidence_refs != recorded.evidence_refs
            ):
                score_bad.append(f"{recorded.proposal_ref}:score-mismatch")
        record("direction_score_integrity", not score_bad, f"violations={score_bad}")

        # Selection integrity: re-apply the closed-set rule.
        resolved = arbiter.select_direction(
            OpportunityGroup(
                schema_version=group.schema_version,
                group_id=group.group_id,
                run_id=group.run_id,
                trace_id=group.trace_id,
                asset=group.asset,
                strategy=group.strategy,
                timeframe=group.timeframe,
                decision_time=group.decision_time,
                long_candidate_ref=group.long_candidate_ref,
                short_candidate_ref=group.short_candidate_ref,
                direction_scores=group.direction_scores,
                selected_direction=SELECTED_NONE,
                selection_reason="",
                counter_evidence=(),
                confidence=0.0,
                created_at=group.created_at,
            ),
            proposals=proposals,
        )
        selection_ok = (
            resolved.selected_direction == group.selected_direction
            and resolved.selection_reason == group.selection_reason
            and resolved.counter_evidence == group.counter_evidence
        )
        record(
            "selection_integrity",
            selection_ok,
            f"expected={resolved.selected_direction}/{resolved.selection_reason} "
            f"recorded={group.selected_direction}/{group.selection_reason}",
        )

        # Counter-evidence integrity: recorded refs must belong to the losing
        # side (EXPECTED_ALTERNATIVE_DIRECTION), never to fabricated sources.
        losing_ref = (
            group.short_candidate_ref
            if group.selected_direction == SELECTED_LONG
            else group.long_candidate_ref
        )
        expected_counter: tuple[str, ...] = ()
        if group.selected_direction != SELECTED_NONE and losing_ref is not None:
            loser = proposals.get(losing_ref)
            if loser is not None:
                expected_counter = tuple(sorted(loser.evidence_refs))
        counter_ok = (
            group.selected_direction == SELECTED_NONE
            or group.counter_evidence == expected_counter
        )
        record(
            "counter_evidence_integrity",
            counter_ok,
            f"expected={expected_counter} recorded={group.counter_evidence}",
        )

        # PIT: proposal data and bound evidence must predate decision time.
        pit_bad: list[str] = []
        for ref in refs:
            proposal = proposals.get(ref)
            if proposal is None:
                continue
            if proposal.data_time > group.decision_time:
                pit_bad.append(f"{ref}:future-proposal")
            for evidence_ref in proposal.evidence_refs:
                evidence = evidence_registry.get(evidence_ref)
                if evidence is None:
                    pit_bad.append(f"{evidence_ref}:unregistered")
                elif getattr(evidence, "available_at", None) is not None and (
                    evidence.available_at > group.decision_time
                ):
                    pit_bad.append(f"{evidence_ref}:future-evidence")
        record("pit_binding", not pit_bad, f"violations={pit_bad}")

        # Replay determinism: group id re-derivation must match (DIR-10).
        replay_id = _group_id(
            {
                "run_id": group.run_id,
                "asset": group.asset,
                "strategy": group.strategy,
                "timeframe": group.timeframe,
                "decision_time": group.decision_time.isoformat(),
                "long_ref": group.long_candidate_ref,
                "short_ref": group.short_candidate_ref,
                "min_direction_score": self.min_direction_score,
            }
        )
        record("group_id_deterministic", replay_id == group.group_id, f"recomputed={replay_id}")

        verdict = (
            GroupVerificationStatus.VERIFIED
            if all(status == "PASS" for _, status, _ in checks)
            else GroupVerificationStatus.REJECTED
        )
        return GroupVerification(
            group_id=group.group_id,
            verdict=verdict,
            checks=tuple(checks),
        )


