"""WP-EDGE-06 — the tick, and the derived reading it now carries.

WP-EDGE-05R found the lane's reconciliation three ticks behind the evidence it reads: it had
been regenerated by hand, and the lane kept writing. The repair is not a bigger convention
("remember to re-run it"), it is that the cadence itself re-reads the lane — so these tests
are about the *decision* and about the *step*, not about the prose describing them:

* a scheduled tick that **consumed its slot** re-reads the lane, and the tick's own record
  carries the instant, the duration and the status of that re-read;
* a tick that changed nothing (already observed, already running, refused for disk) does not
  re-read, and says why in the record rather than leaving the field empty;
* a re-read that **fails** leaves the tick's outcome and exit code exactly as they were: the
  tick observed, and the lane is not the reader.

The step is driven against a synthetic tree, never against the live lane, and the branch is
driven by a fake observer, so a run of this file writes nothing into ``data/forward``.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path
from typing import Any

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]


@pytest.fixture(scope="module")
def observer_module() -> Any:
    path = REPO_ROOT / "scripts" / "edge04_observer.py"
    spec = importlib.util.spec_from_file_location("edge04_observer", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class _FakeObserver:
    """An observer whose tick returns whatever the test declares, and nothing else."""

    def __init__(self, record: dict[str, Any]) -> None:
        self._record = record
        self.ticked = 0

    def tick(self, **_kwargs: Any) -> dict[str, Any]:
        self.ticked += 1
        return dict(self._record)


def _run_tick(
    observer_module: Any,
    monkeypatch: pytest.MonkeyPatch,
    capsys: Any,
    *,
    record: dict[str, Any],
    argv: list[str],
) -> dict[str, Any]:
    fake = _FakeObserver(record)
    monkeypatch.setattr(observer_module, "ForwardObserver", lambda **_kw: fake)
    code = observer_module.main(argv)
    printed = capsys.readouterr().out
    return {"code": code, "payload": json.loads(printed), "observer": fake}


BASE_RECORD: dict[str, Any] = {
    "run_id": "FWD-EDGE04-20261014T000000Z",
    "slot_key": "2026-10-14T00:00Z",
    "mode": "SCHEDULED",
    "outcome": "OBSERVED",
    "outcome_reason": "three new bars",
    "duration_seconds": 1.5,
    "new_bars": 3,
    "market_requests": 6,
    "health_status": "OK",
    "alerts": [],
    "exit_code": 0,
    "disk_after": {"status": "WARNING", "free_gib": 4.2},
    "publication": {"ran": False, "reason": "not due"},
}


def test_a_scheduled_tick_that_consumed_its_slot_re_reads_the_lane(
    observer_module: Any, monkeypatch: pytest.MonkeyPatch, capsys: Any
) -> None:
    calls: list[dict[str, Any]] = []

    def fake_refresh(**kwargs: Any) -> dict[str, Any]:
        calls.append(kwargs)
        return {"ran": True, "reason": None, "seconds": 0.5, "status": "CONSISTENT"}

    monkeypatch.setattr(observer_module, "_refresh_derived", fake_refresh)
    result = _run_tick(
        observer_module,
        monkeypatch,
        capsys,
        record=BASE_RECORD,
        argv=["--scheduled", "--due", "--json"],
    )

    assert calls == [{"outcome": "OBSERVED", "repo_root": observer_module.REPO_ROOT}]
    assert result["payload"]["derived_refresh"]["ran"] is True
    assert result["payload"]["derived_refresh"]["status"] == "CONSISTENT"
    assert result["code"] == 0


@pytest.mark.parametrize("outcome", ["ALREADY_OBSERVED", "ALREADY_RUNNING", "DISK_BUDGET_EXCEEDED"])
def test_a_tick_that_changed_nothing_does_not_re_read_the_lane(
    observer_module: Any, monkeypatch: pytest.MonkeyPatch, capsys: Any, outcome: str
) -> None:
    def forbidden(**_kwargs: Any) -> dict[str, Any]:
        raise AssertionError("a tick that consumed no slot must not re-read the lane")

    monkeypatch.setattr(observer_module, "_refresh_derived", forbidden)
    record = {**BASE_RECORD, "outcome": outcome, "exit_code": 0}
    result = _run_tick(
        observer_module,
        monkeypatch,
        capsys,
        record=record,
        argv=["--scheduled", "--due", "--json"],
    )

    refresh = result["payload"]["derived_refresh"]
    assert refresh["ran"] is False
    assert outcome in refresh["reason"]
    assert refresh["seconds"] == 0.0


def test_a_manual_tick_leaves_the_derived_reading_alone_unless_asked(
    observer_module: Any, monkeypatch: pytest.MonkeyPatch, capsys: Any
) -> None:
    def forbidden(**_kwargs: Any) -> dict[str, Any]:
        raise AssertionError("a manual tick must not re-read the lane by default")

    monkeypatch.setattr(observer_module, "_refresh_derived", forbidden)
    plain = _run_tick(
        observer_module, monkeypatch, capsys, record=BASE_RECORD, argv=["--due", "--json"]
    )
    assert "derived_refresh" not in plain["payload"]

    asked: list[dict[str, Any]] = []
    monkeypatch.setattr(
        observer_module,
        "_refresh_derived",
        lambda **kwargs: asked.append(kwargs) or {"ran": True, "reason": None, "seconds": 0.1},
    )
    explicit = _run_tick(
        observer_module,
        monkeypatch,
        capsys,
        record=BASE_RECORD,
        argv=["--due", "--refresh-derived", "--json"],
    )
    assert asked and explicit["payload"]["derived_refresh"]["ran"] is True


def test_the_re_read_writes_into_the_watchdog_state(
    observer_module: Any, tmp_path: Path
) -> None:
    """The step itself, against a synthetic tree: it reports, it does not decide.

    A lane with no evidence yet is *readable*, not an exception: an empty reconciliation is a
    reading of an empty lane, and the receipt says so. That is why the failure branch is
    driven below by a reconciler that raises, rather than by a tree that does not exist.
    """
    receipt = observer_module._refresh_derived(outcome="OBSERVED", repo_root=tmp_path)
    assert receipt["ran"] is True, receipt
    assert receipt["after_outcome"] == "OBSERVED"
    assert receipt["seconds"] >= 0.0
    report = tmp_path / "data" / "forward" / "edge05" / "reconciliation" / "RECONCILIATION.json"
    assert report.is_file(), receipt
    assert receipt["artifacts"]["reconciliation"] == str(report)


def test_a_failed_re_read_is_recorded_and_changes_nothing_else(
    observer_module: Any, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: Any
) -> None:
    from trading_bot.research.edge05 import reconcile as reconcile_module

    class _Exploding:
        def __init__(self, **_kwargs: Any) -> None:
            raise RuntimeError("the lane's ledger is unreadable")

    monkeypatch.setattr(reconcile_module, "Reconciler", _Exploding)
    failed = observer_module._refresh_derived(outcome="OBSERVED", repo_root=tmp_path)
    assert failed["ran"] is False
    assert "RuntimeError" in failed["reason"]
    assert "ledger is unreadable" in failed["reason"]
    assert failed["after_outcome"] == "OBSERVED"

    # and through the entry point: the tick still reports the outcome it had, with the failed
    # re-read beside it, and the exit code is still the outcome's own.
    record = {**BASE_RECORD, "exit_code": 0}
    result = _run_tick(
        observer_module,
        monkeypatch,
        capsys,
        record=record,
        argv=["--scheduled", "--due", "--json"],
    )
    assert result["payload"]["outcome"] == "OBSERVED"
    assert result["payload"]["derived_refresh"]["ran"] is False
    assert result["code"] == 0
